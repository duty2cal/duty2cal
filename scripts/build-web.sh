# Build the browser bundle for the converter page (design D1).
#
# `wasm-pack` produces the ES-module glue and the matching `wasm-bindgen` CLI
# in one documented command. The wasm bytes are then inlined as one base64 ES
# module, because the page's `connect-src 'none'` CSP forbids the generated
# loader's default `fetch` of the `.wasm` file. The CSP is never weakened.
#
# The script installs exactly the version recorded in web/.wasm-pack-version.
set -euo pipefail
cd "$(dirname "$0")/.."

cargo_bin="$(command -v cargo || true)"
if [ -z "$cargo_bin" ]; then
  echo "build-web: cargo is required" >&2
  exit 1
fi

pin="$(tr -d '[:space:]' < web/.wasm-pack-version)"
wasm_pack="${CARGO_HOME:-$HOME/.cargo}/bin/wasm-pack"
installed=""
if command -v wasm-pack >/dev/null 2>&1; then
  installed="$(wasm-pack --version | awk '{print $2}')"
elif [ -x "$wasm_pack" ]; then
  installed="$("$wasm_pack" --version | awk '{print $2}')"
fi
if [ "$installed" != "$pin" ]; then
  "$cargo_bin" install wasm-pack --version "$pin" --locked
fi

# Run exactly the pinned binary: the one on PATH when it matches, otherwise the
# one the install just wrote.
if [ "$installed" = "$pin" ] && command -v wasm-pack >/dev/null 2>&1; then
  wasm_pack_bin="wasm-pack"
else
  wasm_pack_bin="$wasm_pack"
fi
"$wasm_pack_bin" build ffi/wasm --release --target web --out-dir ../../web/pkg

{
  printf '// SPDX-License-Identifier: MPL-2.0\n'
  printf '// Generated by scripts/build-web.sh; do not edit.\n'
  printf 'export const wasmBase64 = "'
  base64 < web/pkg/duty2cal_wasm_bg.wasm | tr -d '\n'
  printf '";\n'
} > web/pkg/wasm-inline.js

cp LICENSES/MPL-2.0.txt web/LICENSE.txt
